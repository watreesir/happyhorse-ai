const CREATIONS_PAGE_SIZE = 6;

export function getCreationPage(page: number) {
  const totalItems = MOCK_CREATIONS.length;
  const totalPages = Math.max(1, Math.ceil(totalItems / CREATIONS_PAGE_SIZE));
  const currentPage = Math.min(Math.max(page, 1), totalPages);
  const start = (currentPage - 1) * CREATIONS_PAGE_SIZE;
  const items = MOCK_CREATIONS.slice(start, start + CREATIONS_PAGE_SIZE);

  return {
    items,
    totalItems,
    totalPages,
    currentPage,
  };
}
